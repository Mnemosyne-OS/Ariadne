export type Lang = keyof typeof STRINGS;
export type Dict = (typeof STRINGS)['en'];

/**
 * English is the complete reference, so every dictionary is merged OVER it.
 *
 * Returning a locale object directly means one missing key resolves to
 * `undefined`, and the first `.replace()` on it takes down the whole render —
 * a blank cartridge because one sentence was untranslated. Merging degrades
 * that to a single English line, which is a missing label rather than a crash.
 */
export function dictFor(lang: string | undefined): Dict {
  const key = (lang || 'en').slice(0, 2) as Lang;
  return { ...STRINGS.en, ...(STRINGS[key] ?? {}) } as Dict;
}

/** `{name}` substitution. Keeps call sites from chaining .replace(). */
export function fill(tpl: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.split(`{${k}}`).join(String(v)),
    tpl,
  );
}
